#  Fruit Ripeness Checker

fruit = "Mango"
color = "Red"

if fruit == "Mango" : 
    print("It is Mango")

    
    if color == "Green" :
        print("Mango is not ripe")
    elif color == "Yellow" :
        print("Mango is ripe")
    elif color == "Red" :
        print("Mango is overripe")

    else:
        print("It is not Mango")
       
       







